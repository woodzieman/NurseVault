        LMSRow(ageMonths: 143.5, l: -0.850915987, m: 40.26827652, s: 0.196281418),
        LMSRow(ageMonths: 144.5, l: -0.836961905, m: 40.67443658, s: 0.196591612),
    ]

    /// LMS z-score for a measured value at a given age, linearly interpolated between
    /// the surrounding table rows (mirrors the source `zScoreInterp`).
    static func zScore(table: [LMSRow], ageMonths: Double, value: Double) -> Double {
        var upper = table.count - 1
        for i in 0...table.count - 1 {
            if ageMonths <= table[i].ageMonths { upper = i; break }
        }
        let z2 = lmsZ(table[upper], value: value)
        guard upper > 0 else { return z2 }
        let z1 = lmsZ(table[upper - 1], value: value)
        let f = (ageMonths - table[upper - 1].ageMonths) / (table[upper].ageMonths - table[upper - 1].ageMonths)
        return z1 + (z2 - z1) * f
    }

    /// LMS z-score at one table row: ((value / M) ^ L − 1) / (L × S).
    private static func lmsZ(_ row: LMSRow, value: Double) -> Double {
        (pow(value / row.m, row.l) - 1) / (row.l * row.s)
    }
